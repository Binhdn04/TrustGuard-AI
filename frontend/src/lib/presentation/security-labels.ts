export function securityLabel(value: string | null | undefined, fallback = "Chưa xác định"): string {
  if (!value) return fallback;
  return LABELS[value] ?? value.replaceAll("_", " ");
}

export function statusLabel(value: string | null | undefined): string {
  return securityLabel(value, "Chưa có trạng thái");
}

export function riskLabel(value: string | null | undefined): string {
  return securityLabel(value, "Chưa có kết luận rủi ro");
}

export function verdictLabel(value: string | null | undefined): string {
  return securityLabel(value, "Chưa có kết luận");
}

export function lifecycleLabel(value: string | null | undefined): string {
  return securityLabel(value, "Chưa có vòng đời");
}

export function decisionLabel(value: string | null | undefined): string {
  return securityLabel(value, "Chưa có quyết định");
}
